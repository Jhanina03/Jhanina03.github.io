/* Small helper used by every page */
window.i18n = {
  lang: "en",
  init() {
    let saved = null;
    try { saved = localStorage.getItem("jc-lang"); } catch (e) {}
    const q = new URLSearchParams(location.search).get("lang"); // shareable ?lang=es links
    if (q === "es" || q === "en") saved = q;
    this.lang = saved === "es" || saved === "en" ? saved : "en";
    this.apply();
  },
  t(key) { return (I18N[this.lang] && I18N[this.lang][key]) || I18N.en[key] || key; },
  pick(v) { return v && typeof v === "object" ? v[this.lang] || v.en : v; },
  set(lang) {
    this.lang = lang;
    try { localStorage.setItem("jc-lang", lang); } catch (e) {}
    this.apply();
    document.dispatchEvent(new CustomEvent("langchange", { detail: lang }));
  },
  apply() {
    document.documentElement.lang = this.lang;
    document.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = this.t(el.dataset.i18n)));
    document.querySelectorAll("[data-i18n-html]").forEach((el) => (el.innerHTML = this.t(el.dataset.i18nHtml)));
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", this.t(el.dataset.i18nAria)));
    const tk = document.body && document.body.dataset.titleKey;
    if (tk) document.title = this.t(tk);
    document.querySelectorAll(".lang-toggle [data-lang]").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.lang === this.lang)));
  },
};
